import { canonicalJson, sha256 } from "./lock.js";

type Json = Record<string, unknown>;

const isObject = (value: unknown): value is Json => typeof value === "object" && value !== null && !Array.isArray(value);

export function stamp(path: string, content: string, version: string, sourceHash: string): string {
  const header = `@generated by warden ${version} from ${sourceHash} sha256:${sha256(content)}`;
  if (path.endsWith(".json")) {
    const body: unknown = JSON.parse(content);
    if (!isObject(body)) throw new Error(`${path} must hold a JSON object to carry a generated header`);
    return `${JSON.stringify({ "@generated": header, ...body }, null, 2)}\n`;
  }
  if (/\.(js|mjs|ts)$/.test(path)) return `// ${header}\n${content}`;
  throw new Error(`cannot place a generated header in ${path}`);
}

const runsWardenCheck = (entry: unknown): boolean =>
  isObject(entry) &&
  Array.isArray(entry.hooks) &&
  entry.hooks.some((h) => isObject(h) && typeof h.command === "string" && h.command.includes("warden check"));

export const isWardenEntry = (entry: unknown, ours: Set<string>): boolean => ours.has(canonicalJson(entry)) || runsWardenCheck(entry);

export function mergeSettings(file: string, existing: string | undefined, owned: Record<string, unknown[]>): string {
  let settings: unknown = {};
  if (existing !== undefined) {
    try {
      settings = JSON.parse(existing);
    } catch (cause) {
      throw new Error(`${file} is not valid JSON: ${(cause as Error).message}`);
    }
  }
  if (!isObject(settings)) throw new Error(`${file} must hold a JSON object`);
  for (const [path, entries] of Object.entries(owned)) {
    const keys = path.split(".");
    const leaf = keys.pop() as string;
    let node: Json = settings;
    for (const key of keys) {
      const next = node[key] ?? {};
      if (!isObject(next)) throw new Error(`${file} ${key} must be an object`);
      node[key] = next;
      node = next;
    }
    const current = node[leaf] ?? [];
    if (!Array.isArray(current)) throw new Error(`${file} ${path} must be an array`);
    const ours = new Set(entries.map(canonicalJson));
    node[leaf] = [...current.filter((e) => !isWardenEntry(e, ours)), ...entries];
  }
  return `${JSON.stringify(settings, null, 2)}\n`;
}
