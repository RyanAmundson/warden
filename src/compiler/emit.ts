import { sha256 } from "./lock.js";

const isObject = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value);

export function stamp(path: string, content: string, version: string, sourceHash: string): string {
  const header = `@generated by warden ${version} from ${sourceHash} sha256:${sha256(content)}`;
  if (path.endsWith(".json")) {
    const body: unknown = JSON.parse(content);
    if (!isObject(body)) throw new Error(`${path} must hold a JSON object to carry a generated header`);
    return `${JSON.stringify({ "@generated": header, ...body }, null, 2)}\n`;
  }
  if (path.endsWith(".md")) {
    if (!content.startsWith("---\n")) throw new Error(`${path} must start with front matter to carry a generated header`);
    return `---\ngenerated: '${header}'\n${content.slice(4)}`;
  }
  if (/\.(js|mjs|ts)$/.test(path)) return `// ${header}\n${content}`;
  if (content.startsWith("#!")) return content.replace("\n", `\n# ${header}\n`);
  throw new Error(`cannot place a generated header in ${path}`);
}

export const COMMIT_HOOK = ".warden/generated/hooks/pre-commit";
export const COMMAND_REPLACEMENTS = ".warden/generated/hooks/command-replacements.json";

export const literalCommand = (source: string): string => source.replace(/^[ \t]+|[ \t]+$/g, "").replace(/[ \t]+/g, " ");

export const RELEASES = "git+https://github.com/RyanAmundson/warden.git";

const quoted = (word: string): string => `'${word.replaceAll("'", "'\\''")}'`;

export const commitHook = (version: string, base: string): string =>
  [
    "#!/bin/sh",
    "if ! command -v warden >/dev/null 2>&1; then",
    `  echo "Warden's commit check needs the global warden command, and it is not on PATH. Next action: run npm install -g ${RELEASES}#v${version}, then commit again." >&2`,
    "  exit 2",
    "fi",
    `exec warden check --base ${quoted(base)} --trigger git-commit`,
    "",
  ].join("\n");
