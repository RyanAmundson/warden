import type { Rule } from "eslint";

interface WardenOptions {
  practice: string;
  statement: string;
}

const SUPPRESSION_COMMENT = /(eslint-disable|eslint-enable|@ts-ignore|@ts-expect-error|@ts-nocheck)/;
const TEST_FUNCTIONS = new Set(["describe", "it", "test"]);
const SKIP_MODIFIERS = new Set(["skip", "only", "todo"]);
const DISABLED_FUNCTIONS = new Set(["xit", "xdescribe"]);

const meta = {
  type: "problem",
  schema: [
    {
      type: "object",
      required: ["practice", "statement"],
      properties: { practice: { type: "string" }, statement: { type: "string" } },
      additionalProperties: true,
    },
  ],
  messages: { violation: "{{text}}" },
} as const satisfies Rule.RuleMetaData;

const textOf = (context: Rule.RuleContext): string => {
  const options = context.options[0] as WardenOptions;
  return `${options.practice}: ${options.statement}`;
};

const isAllowedComment = (comment: { type: string; value: string; range?: [number, number] }): boolean => {
  const value = comment.value;
  if (comment.type === "Shebang") return true;
  if (comment.type === "Line") {
    if (comment.range?.[0] === 0 && value.startsWith("!")) return true;
    if (value.startsWith("/ <reference ")) return true;
  }
  if (comment.type === "Block" && value.includes("@vitest-environment")) return true;
  return value.trim().startsWith("@generated by warden");
};

const noComments: Rule.RuleModule = {
  meta,
  create(context) {
    const text = textOf(context);
    return {
      Program() {
        for (const comment of context.sourceCode.getAllComments()) {
          if (isAllowedComment(comment) || comment.loc == null) continue;
          context.report({ loc: comment.loc, messageId: "violation", data: { text } });
        }
      },
    };
  },
};

const noSuppressions: Rule.RuleModule = {
  meta,
  create(context) {
    const text = textOf(context);
    return {
      Program() {
        for (const comment of context.sourceCode.getAllComments()) {
          if (comment.loc == null || !SUPPRESSION_COMMENT.test(comment.value)) continue;
          context.report({ loc: comment.loc, messageId: "violation", data: { text } });
        }
      },
      CallExpression(node) {
        const callee = node.callee;
        const skipped =
          callee.type === "MemberExpression" &&
          callee.object.type === "Identifier" &&
          TEST_FUNCTIONS.has(callee.object.name) &&
          callee.property.type === "Identifier" &&
          SKIP_MODIFIERS.has(callee.property.name);
        const disabled = callee.type === "Identifier" && DISABLED_FUNCTIONS.has(callee.name);
        if (skipped || disabled) context.report({ node, messageId: "violation", data: { text } });
      },
    };
  },
};

export const plugin = {
  meta: { name: "warden" },
  rules: { "no-comments": noComments, "no-suppressions": noSuppressions },
};
