import type { Rule } from "eslint";
import type { Comment, Identifier, Node } from "estree";

interface WardenOptions {
  practice: string;
  statement: string;
}

const SUPPRESSION_COMMENT = /(eslint-disable|eslint-enable|@ts-ignore|@ts-expect-error|@ts-nocheck)/;
const TEST_ROOTS = new Set(["describe", "it", "test", "suite", "bench"]);
const SKIP_MODIFIERS = new Set(["skip", "only", "todo", "skipIf", "runIf", "fails"]);
const GLOBAL_OBJECTS = new Set(["globalThis", "global", "window", "self"]);
const MAX_ALIASES = 8;
const DISABLED_FUNCTIONS = new Set(["xit", "xdescribe", "xtest", "fit", "fdescribe"]);
const REFERENCE_DIRECTIVE = /^\/\s*<reference\s+(path|types|lib|no-default-lib)=("[^"\s]+"|'[^'\s]+')\s*\/>\s*$/;
const GENERATED_HEADER = /^\s*@generated by warden \d+\.\d+\.\d+ from [0-9a-f]+ sha256:[0-9a-f]{64}\s*$/;
const ENVIRONMENT_TAG = /^\s*@vitest-environment\s+(node|jsdom|happy-dom|edge-runtime)\s*$/;

const meta = {
  type: "problem",
  schema: [
    {
      type: "object",
      required: ["practice", "statement"],
      properties: { practice: { type: "string" }, statement: { type: "string" } },
      additionalProperties: true,
    },
  ],
  messages: { violation: "{{text}}" },
} as const satisfies Rule.RuleMetaData;

const textOf = (context: Rule.RuleContext): string => {
  const options = context.options[0] as WardenOptions;
  return `${options.practice}: ${options.statement}`;
};

const isAllowedComment = (comment: Comment, firstTokenStart: number): boolean => {
  const atStart = comment.range?.[0] === 0;
  if ((comment.type as string) === "Shebang") return true;
  if (atStart && GENERATED_HEADER.test(comment.value)) return true;
  const leading = (comment.range?.[1] ?? Infinity) <= firstTokenStart;
  if (comment.type === "Line" && leading && REFERENCE_DIRECTIVE.test(comment.value)) return true;
  return comment.type === "Block" && leading && ENVIRONMENT_TAG.test(comment.value);
};

const noComments: Rule.RuleModule = {
  meta,
  create(context) {
    const text = textOf(context);
    return {
      Program(program) {
        const firstTokenStart = program.body[0]?.range?.[0] ?? Infinity;
        for (const comment of context.sourceCode.getAllComments()) {
          if (isAllowedComment(comment, firstTokenStart) || comment.loc == null) continue;
          context.report({ loc: comment.loc, messageId: "violation", data: { text } });
        }
      },
    };
  },
};

const WRAPPERS = new Set(["TSAsExpression", "TSNonNullExpression", "TSSatisfiesExpression", "TSTypeAssertion", "ChainExpression", "TSInstantiationExpression"]);

const unwrap = (node: Node): Node =>
  WRAPPERS.has(node.type) ? (node as unknown as { expression: Node }).expression : node;

const chainOf = (callee: Node, context: Rule.RuleContext, depth = 0): { root?: string; props: string[] } => {
  const props: string[] = [];
  let node: Node = callee;
  for (;;) {
    const wrapped = unwrap(node);
    if (wrapped !== node) {
      node = wrapped;
    } else if (node.type === "MemberExpression") {
      const { property, computed } = node;
      if (!computed && property.type === "Identifier") props.push(property.name);
      else if (property.type === "Literal" && typeof property.value === "string") props.push(property.value);
      else if (property.type === "TemplateLiteral" && property.expressions.length === 0) {
        props.push(property.quasis[0]?.value.cooked ?? "");
      }
      node = node.object;
    } else if (node.type === "CallExpression") {
      node = node.callee;
    } else if (node.type === "Identifier" && GLOBAL_OBJECTS.has(node.name) && props.length > 0) {
      return { root: props.pop(), props };
    } else if (node.type === "Identifier") {
      const known = TEST_ROOTS.has(node.name) || DISABLED_FUNCTIONS.has(node.name);
      const alias = known || depth >= MAX_ALIASES ? undefined : aliasOf(node, context, depth);
      return alias === undefined ? { root: node.name, props } : { root: alias.root, props: [...props, ...alias.props] };
    } else {
      return { props };
    }
  }
};

const aliasOf = (id: Identifier, context: Rule.RuleContext, depth: number): { root?: string; props: string[] } | undefined => {
  const reference = context.sourceCode.getScope(id).references.find((r) => r.identifier === id);
  const def = reference?.resolved?.defs[0];
  if (def?.type !== "Variable" || def.node.init == null) return undefined;
  const init = chainOf(def.node.init, context, depth + 1);
  if (def.node.id.type === "Identifier") return init;
  if (def.node.id.type !== "ObjectPattern") return undefined;
  const property = def.node.id.properties.find((p) => p.type === "Property" && p.value === def.name);
  if (property?.type !== "Property" || property.computed || property.key.type !== "Identifier") return undefined;
  return { root: init.root, props: [property.key.name, ...init.props] };
};

const noSuppressions: Rule.RuleModule = {
  meta,
  create(context) {
    const text = textOf(context);
    return {
      Program() {
        for (const comment of context.sourceCode.getAllComments()) {
          if (comment.loc == null || !SUPPRESSION_COMMENT.test(comment.value)) continue;
          context.report({ loc: comment.loc, messageId: "violation", data: { text } });
        }
      },
      CallExpression(node) {
        const parent = node.parent;
        if (parent.type === "CallExpression" && parent.callee === node) return;
        const { root, props } = chainOf(node.callee, context);
        if (root === undefined) return;
        const skipped = TEST_ROOTS.has(root) && props.some((p) => SKIP_MODIFIERS.has(p));
        if (skipped || DISABLED_FUNCTIONS.has(root)) context.report({ node, messageId: "violation", data: { text } });
      },
    };
  },
};

export const plugin = {
  meta: { name: "warden" },
  rules: { "no-comments": noComments, "no-suppressions": noSuppressions },
};
