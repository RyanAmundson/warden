import { createHash } from "node:crypto";
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { compile } from "../../src/compiler/compile.js";
import { runExamples } from "../../src/compiler/examples.js";
import { loadRecords } from "../../src/records/load.js";
import { readLock } from "../../src/compiler/lock.js";

const wardenRoot = resolve(import.meta.dirname, "../..");
const fixture = resolve(import.meta.dirname, "../fixtures/project-valid");
const HEADER = /^@generated by warden \d+\.\d+\.\d+ from [0-9a-f]{64} sha256:[0-9a-f]{64}$/;

let root: string;

const localPack = (guardrail: string, practiceExtra = ""): string =>
  [
    "id: local",
    "layer: 1",
    "terms: []",
    "practices:",
    "  - id: local-practice",
    "    statement: Declare with const.",
    "    terms: []",
    "    paths: []",
    "    conflictsWith: []",
    guardrail,
    practiceExtra,
  ].join("\n");

const usePack = async (pack: string): Promise<void> => {
  const config = join(root, ".warden/config.yaml");
  await writeFile(config, `${await readFile(config, "utf8")}`.replace("tierBudgetMs:", "  - id: local\n    paths: [\"src/**\"]\ntierBudgetMs:"));
  await mkdir(join(root, ".warden/packs/local"), { recursive: true });
  await writeFile(join(root, ".warden/packs/local/pack.yaml"), pack);
};

const read = (file: string): Promise<string> => readFile(join(root, file), "utf8");

beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), "warden-compile-"));
  await cp(fixture, root, { recursive: true });
});

afterEach(() => rm(root, { recursive: true, force: true }));

describe("compile", () => {
  it("compile writes config, deny rules, and lock", async () => {
    const { findings, written } = await compile(root, wardenRoot);
    expect(findings).toEqual([]);
    expect(written.sort()).toEqual([".claude/settings.json", ".warden/generated/eslint.rules.json", ".warden/lock.json"]);
    const rules = JSON.parse(await read(".warden/generated/eslint.rules.json"));
    expect(rules["@generated"]).toMatch(HEADER);
    expect(Object.keys(rules)[0]).toBe("@generated");
    expect(Array.isArray(rules.entries)).toBe(true);
    const settings = JSON.parse(await read(".claude/settings.json"));
    expect(settings.permissions.deny).toEqual(["Edit(.warden/**)", "Write(.warden/**)", "Bash(git commit*--no-verify*)", "Bash(git commit -n*)"]);
    const lock = readLock(root);
    expect(Object.keys(lock.generated).sort()).toEqual([
      ".claude/settings.json#warden",
      ".warden/generated/eslint.rules.json",
    ]);
    expect(Object.keys(lock.sources).sort()).toEqual([".warden/config.yaml", "packs/core/pack.yaml"]);
    expect(lock.guardrails["warden-no-comments"]).toEqual({
      kind: "lint",
      budgetMs: 5000,
      version: 1,
      implementation: "eslint:warden/no-comments",
      options: null,
      runs: ["commit", "edit"],
      paths: ["**/*.{ts,tsx,mts,cts,js,mjs,cjs} & src/**"],
    });
    expect(lock.format).toBe(1);
    expect(lock.config).toEqual({ project: "fixture", base: "main", tierBudgetMs: { edit: 2000, commit: 30000, boundary: 120000 }, loopBreakerRepeats: 3 });
  });

  it("lock hashes the emitted bytes", async () => {
    await compile(root, wardenRoot);
    const lock = readLock(root);
    const bytes = await read(".warden/generated/eslint.rules.json");
    expect(lock.generated[".warden/generated/eslint.rules.json"]).toBe(createHash("sha256").update(bytes).digest("hex"));
  });

  it("deny merge keeps other settings", async () => {
    await mkdir(join(root, ".claude"), { recursive: true });
    await writeFile(join(root, ".claude/settings.json"), JSON.stringify({ model: "x", permissions: { allow: ["Read"], deny: ["Bash(rm*)"] } }));
    await compile(root, wardenRoot);
    const settings = JSON.parse(await read(".claude/settings.json"));
    expect(settings.model).toBe("x");
    expect(settings.permissions.allow).toEqual(["Read"]);
    expect(settings.permissions.deny).toEqual(["Bash(rm*)", "Edit(.warden/**)", "Write(.warden/**)", "Bash(git commit*--no-verify*)", "Bash(git commit -n*)"]);
  });

  it("compile registers the edit-tier hook once", async () => {
    const other = { matcher: "Bash", hooks: [{ type: "command", command: "echo hi" }] };
    await mkdir(join(root, ".claude"), { recursive: true });
    await writeFile(join(root, ".claude/settings.json"), JSON.stringify({ hooks: { PostToolUse: [other] } }));
    await compile(root, wardenRoot);
    const first = await read(".claude/settings.json");
    const lockFirst = readLock(root);
    await compile(root, wardenRoot);
    expect(await read(".claude/settings.json")).toBe(first);
    expect(readLock(root).generated[".claude/settings.json#warden"]).toBe(lockFirst.generated[".claude/settings.json#warden"]);
    const entries = JSON.parse(first).hooks.PostToolUse as { matcher: string; hooks: { command: string }[] }[];
    expect(entries).toHaveLength(2);
    expect(entries[0]).toEqual(other);
    expect(entries[1]).toEqual({
      matcher: "Edit|Write|MultiEdit",
      hooks: [{ type: "command", command: "npx --no -- warden check --format agent --hook claude --base 'main'" }],
    });
    expect(first.endsWith("}\n")).toBe(true);
  });

  it("settings edits outside Warden entries do not change the settings lock hash", async () => {
    await compile(root, wardenRoot);
    const before = readLock(root).generated[".claude/settings.json#warden"];
    const settings = JSON.parse(await read(".claude/settings.json"));
    await writeFile(join(root, ".claude/settings.json"), JSON.stringify({ ...settings, model: "y" }));
    await compile(root, wardenRoot);
    expect(readLock(root).generated[".claude/settings.json#warden"]).toBe(before);
  });

  it("findings block writing", async () => {
    await usePack(
      localPack(
        [
          "    guardrails:",
          "      - id: local-prose",
          "        kind: instruction",
          "        runs: [edit]",
          "        budgetMs: 100",
          "        version: 1",
          "        implementation: \"instruction:CLAUDE.md\"",
          "        mustFail: \"x\"",
          "        mustPass: \"y\"",
        ].join("\n"),
      ),
    );
    const { findings, written } = await compile(root, wardenRoot);
    expect(findings.map((f) => f.code)).toEqual(["prose-only"]);
    expect(written).toEqual([]);
    await expect(readFile(join(root, ".warden/lock.json"))).rejects.toThrow();
    await expect(readFile(join(root, ".claude/settings.json"))).rejects.toThrow();
  });

  it("slow examples are rejected", async () => {
    await usePack(
      localPack(
        [
          "    guardrails:",
          "      - id: local-no-var",
          "        kind: lint",
          "        runs: [edit]",
          "        budgetMs: 1",
          "        version: 1",
          "        implementation: \"eslint:no-var\"",
          "        mustFail: \"var a = 1;\\n\"",
          "        mustPass: \"const a = 1;\\n\"",
        ].join("\n"),
      ),
    );
    const { findings, written } = await compile(root, wardenRoot);
    expect(findings.length).toBeGreaterThan(0);
    expect(findings.every((f) => f.code === "over-budget" && f.record === "local-no-var")).toBe(true);
    expect(written).toEqual([]);
  });

  it("a mustFail example that passes is rejected", async () => {
    await usePack(
      localPack(
        [
          "    guardrails:",
          "      - id: local-no-var",
          "        kind: lint",
          "        runs: [edit]",
          "        budgetMs: 5000",
          "        version: 1",
          "        implementation: \"eslint:no-var\"",
          "        mustFail: \"const a = 1;\\n\"",
          "        mustPass: \"var a = 1;\\n\"",
        ].join("\n"),
      ),
    );
    const { findings, written } = await compile(root, wardenRoot);
    expect(findings.map((f) => `${f.code} ${f.record}`)).toEqual(["example-failed local-no-var", "example-failed local-no-var"]);
    expect(written).toEqual([]);
  });

  it("an example that does not parse is a finding", async () => {
    await usePack(
      localPack(
        [
          "    guardrails:",
          "      - id: local-no-var",
          "        kind: lint",
          "        runs: [edit]",
          "        budgetMs: 5000",
          "        version: 1",
          "        implementation: \"eslint:no-var\"",
          "        mustFail: \"var a = 1;\\n\"",
          "        mustPass: \"const = ;\\n\"",
        ].join("\n"),
      ),
    );
    const { findings, written } = await compile(root, wardenRoot);
    expect(findings.map((f) => `${f.code} ${f.record} ${f.message}`)).toContain(
      "example-failed local-no-var Guardrail local-no-var mustPass example does not parse.",
    );
    expect(written).toEqual([]);
  });

  it("checks tsc examples and emits their config with a header", async () => {
    await usePack(
      localPack(
        [
          "    guardrails:",
          "      - id: local-no-implicit-any",
          "        kind: type",
          "        runs: [commit]",
          "        budgetMs: 60000",
          "        version: 1",
          "        implementation: \"tsc:noImplicitAny\"",
          "        mustFail: \"export function f(a) { return a; }\\n\"",
          "        mustPass: \"export const a: number = 1;\\n\"",
        ].join("\n"),
      ),
    );
    const { findings, written } = await compile(root, wardenRoot);
    expect(findings).toEqual([]);
    expect(written).toContain(".warden/generated/tsconfig.json");
    expect(JSON.parse(await read(".warden/generated/tsconfig.json"))["@generated"]).toMatch(HEADER);
  });

  it("a mustPass example that fails another guardrail is an example-conflict", async () => {
    const guardrail = (id: string, rule: string, fail: string, pass: string): string =>
      [
        `      - id: ${id}`,
        "        kind: lint",
        "        runs: [edit]",
        "        budgetMs: 5000",
        "        version: 1",
        `        implementation: "eslint:${rule}"`,
        `        mustFail: ${JSON.stringify(fail)}`,
        `        mustPass: ${JSON.stringify(pass)}`,
      ].join("\n");
    await usePack(
      localPack(
        [
          "    guardrails:",
          guardrail("local-no-var", "no-var", "var a = 1;\n", "let a = 1;\n"),
          guardrail("local-prefer-const", "prefer-const", "let a = 1;\n", "const a = 1;\n"),
        ].join("\n"),
      ),
    );
    const set = await loadRecords(root, wardenRoot);
    const findings = await runExamples(set, wardenRoot);
    expect(findings.map((f) => `${f.code} ${f.record}`)).toEqual(["example-conflict local-no-var"]);
    expect(findings[0]?.message).toContain("local-prefer-const");
  });

  it("a mustPass example is checked only against Guardrails enabled on its path", async () => {
    const practice = (id: string, paths: string, kind: string, implementation: string, fail: string, pass: string): string =>
      [
        `  - id: ${id}`,
        "    statement: Declare with const.",
        "    terms: []",
        `    paths: ${paths}`,
        "    conflictsWith: []",
        "    guardrails:",
        `      - id: ${id}-g`,
        `        kind: ${kind}`,
        "        runs: [edit]",
        "        budgetMs: 60000",
        "        version: 1",
        `        implementation: "${implementation}"`,
        `        mustFail: ${JSON.stringify(fail)}`,
        `        mustPass: ${JSON.stringify(pass)}`,
      ].join("\n");
    const unsafe = "export function f(a?: string) { return a.length; }\n";
    await usePack(
      [
        "id: local",
        "layer: 1",
        "terms: []",
        "practices:",
        practice("in-a", '["src/a/**"]', "lint", "eslint:no-var", "var a = 1;\n", unsafe),
        practice("in-b", '["src/b/**"]', "type", "tsc:strictNullChecks", unsafe, "export const a = 1;\n"),
        "",
      ].join("\n"),
    );
    expect(await runExamples(await loadRecords(root, wardenRoot), wardenRoot)).toEqual([]);
    await writeFile(
      join(root, ".warden/packs/local/pack.yaml"),
      [
        "id: local",
        "layer: 1",
        "terms: []",
        "practices:",
        practice("in-a", '["src/**"]', "lint", "eslint:no-var", "var a = 1;\n", unsafe),
        practice("in-b", '["src/**"]', "type", "tsc:strictNullChecks", unsafe, "export const a = 1;\n"),
        "",
      ].join("\n"),
    );
    expect((await runExamples(await loadRecords(root, wardenRoot), wardenRoot)).map((f) => `${f.code} ${f.record}`)).toEqual(["example-conflict in-a-g"]);
  });

  it("an unknown adapter fails compile, writes no lock, and its next action compiles", async () => {
    await usePack(
      localPack(
        [
          "    guardrails:",
          "      - id: local-no-var",
          "        kind: lint",
          "        runs: [edit]",
          "        budgetMs: 5000",
          "        version: 1",
          "        implementation: \"eslnt:no-var\"",
          "        mustFail: \"var a = 1;\\n\"",
          "        mustPass: \"const a = 1;\\n\"",
        ].join("\n"),
      ),
    );
    const file = join(root, ".warden/packs/local/pack.yaml");
    const { findings, written } = await compile(root, wardenRoot);
    expect(findings).toEqual([
      {
        code: "unknown-adapter",
        record: "local-no-var",
        message: `Guardrail local-no-var names adapter "eslnt", which is not registered; the known adapters are eslint, tsc, cmd. Next action: set implementation to one of eslint:<...>, tsc:<...>, cmd:<...> in ${file}.`,
      },
    ]);
    expect(written).toEqual([]);
    await expect(readFile(join(root, ".warden/lock.json"))).rejects.toThrow();
    await writeFile(file, (await readFile(file, "utf8")).replace("eslnt:", "eslint:"));
    expect((await compile(root, wardenRoot)).findings).toEqual([]);
  });

  it("invalid settings JSON leaves no generated file, no settings change, and no lock", async () => {
    await mkdir(join(root, ".claude"), { recursive: true });
    await writeFile(join(root, ".claude/settings.json"), "{ not json");
    await expect(compile(root, wardenRoot)).rejects.toThrow(".claude/settings.json is not valid JSON");
    expect(await read(".claude/settings.json")).toBe("{ not json");
    await expect(readFile(join(root, ".warden/generated/eslint.rules.json"))).rejects.toThrow();
    await expect(readFile(join(root, ".warden/lock.json"))).rejects.toThrow();
  });
});
