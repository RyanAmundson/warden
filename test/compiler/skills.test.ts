import { execFileSync, spawnSync } from "node:child_process";
import { cp, mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { refusal } from "../../src/adapters/claude.js";
import { compile } from "../../src/compiler/compile.js";
import { checkConsistency } from "../../src/compiler/consistency.js";
import { stamp } from "../../src/compiler/emit.js";
import { readLock } from "../../src/compiler/lock.js";
import { SKILLS_DIR, checkCommands, skillPath } from "../../src/compiler/skills.js";
import { loadRecords } from "../../src/records/load.js";
import { doctor } from "../../src/runner/doctor.js";
import { readEvidence } from "../../src/runner/evidence.js";
import { findTampering } from "../../src/runner/tamper.js";
import { parse } from "yaml";

const wardenRoot = resolve(import.meta.dirname, "../..");
const fixture = resolve(import.meta.dirname, "../fixtures/project-valid");
const HEADER = /^generated: '@generated by warden \d+\.\d+\.\d+ from [0-9a-f]{64} sha256:[0-9a-f]{64}'$/;
const REPLACEMENT_POLICY = ".warden/generated/hooks/command-replacements.json";

let root: string;
let home: string;

const capability = (id: string, kind: string, serves: string, commands: string[], replaces: (string | { command: string })[] = [], purpose = "Gate a unit before review.", when = "a unit is ready for review"): string[] => [
  `  - id: ${id}`,
  `    kind: ${kind}`,
  `    serves: ${serves}`,
  `    purpose: ${JSON.stringify(purpose)}`,
  `    when: ${JSON.stringify(when)}`,
  "    upholds: [no-comments, no-suppressions]",
  `    commands: ${JSON.stringify(commands)}`,
  `    replaces: ${JSON.stringify(replaces)}`,
];

const usePack = async (capabilities: string[]): Promise<void> => {
  const config = join(root, ".warden/config.yaml");
  const text = await readFile(config, "utf8");
  if (!text.includes("id: local")) await writeFile(config, text.replace("tierBudgetMs:", "  - id: local\n    paths: [\"src/**\"]\ntierBudgetMs:"));
  await mkdir(join(root, ".warden/packs/local"), { recursive: true });
  const pack = [
    "id: local",
    "layer: 1",
    "terms:",
    "  - { id: review, definition: Checking a unit before it lands., bans: [] }",
    "  - { id: lookup, definition: Finding where a thing lives., bans: [] }",
    "practices: []",
    "capabilities:",
    ...capabilities,
    "",
  ];
  await writeFile(join(root, ".warden/packs/local/pack.yaml"), pack.join("\n"));
};

const gate = (replaces: (string | { command: string })[] = ["old-gate"]): string[] => capability("review-gate", "skill", "review", ["warden check --rule no-comments", "warden doctor"], replaces);

const bash = (command: string): string => JSON.stringify({ tool_name: "Bash", tool_input: { command } });

const guard = (command: string) => spawnSync("sh", [join(wardenRoot, "hooks/warden.sh"), "guard"], {
  cwd: root,
  env: { ...process.env, PATH: `${join(home, "bin")}:${process.env.PATH ?? ""}` },
  input: bash(command),
  encoding: "utf8",
});

beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), "warden-skills-"));
  home = await mkdtemp(join(tmpdir(), "warden-home-"));
  vi.stubEnv("WARDEN_HOME", home);
  await cp(fixture, root, { recursive: true });
});

afterEach(async () => {
  vi.unstubAllEnvs();
  await rm(root, { recursive: true, force: true });
  await rm(home, { recursive: true, force: true });
});

describe("skill capabilities", () => {
  it("compiles only literal command replacements into the harness guard and removes retired policy", async () => {
    execFileSync("git", ["init", "-b", "main", "-q"], { cwd: root });
    await mkdir(join(home, "bin"));
    await symlink(join(wardenRoot, "bin/warden.js"), join(home, "bin/warden"));
    await usePack(gate(["printf hand-review", { command: "printf  legacy-report" }]));
    expect((await compile(root, wardenRoot)).findings).toEqual([]);
    expect(readLock(root).generated[REPLACEMENT_POLICY]).toMatch(/^[a-f0-9]{64}$/);
    const refused = guard(" printf\tlegacy-report ");
    expect(refused.status).toBe(0);
    const deny = JSON.parse(refused.stdout) as { hookSpecificOutput: Record<string, string> };
    expect(deny.hookSpecificOutput).toMatchObject({
      hookEventName: "PreToolUse",
      permissionDecision: "deny",
      permissionDecisionReason: expect.stringContaining("Capability review-gate"),
    });
    for (const command of ["printf hand-review", "printf legacy-report preview", "warden check --rule no-comments", "warden doctor"]) {
      expect(refusal(root, bash(command))).toBeUndefined();
    }
    expect(readEvidence("fixture").filter((entry) => entry.kind === "tampered")).toEqual([
      expect.objectContaining({ detail: "capability-replacement:review-gate", next: expect.stringContaining("warden check --rule no-comments") }),
    ]);
    const policy = await readFile(join(root, REPLACEMENT_POLICY));
    await rm(join(root, REPLACEMENT_POLICY));
    expect(() => refusal(root, bash("pwd"))).toThrow("Command replacements differ from the compiled lock");
    await writeFile(join(root, REPLACEMENT_POLICY), policy);
    await usePack(gate(["printf hand-review"]));
    expect((await compile(root, wardenRoot)).findings).toEqual([]);
    expect(existsSync(join(root, REPLACEMENT_POLICY))).toBe(false);
    expect(refusal(root, bash("printf legacy-report"))).toBeUndefined();
    const lock = readLock(root);
    const guardrail = Object.values(lock.guardrails)[0];
    if (guardrail === undefined) throw new Error("The fixture lock needs a Guardrail");
    guardrail.options = REPLACEMENT_POLICY;
    await writeFile(join(root, ".warden/lock.json"), JSON.stringify(lock));
    expect(refusal(root, bash("pwd"))).toBeUndefined();
    await writeFile(join(root, ".warden/lock.json"), "{");
    expect(refusal(root, bash("pwd"))).toBeUndefined();
  });

  it("rejects duplicate replacements and replacements of a registered command", async () => {
    await usePack([
      ...gate([{ command: "warden  report" }, { command: "printf legacy-report" }]),
      ...capability("lookup-tool", "tool", "lookup", ["warden report"], [{ command: "printf  legacy-report" }]),
    ]);
    const checked = await compile(root, wardenRoot);
    expect(checked.findings.map(({ code, record }) => [code, record])).toEqual([
      ["registered-command-replacement", "review-gate"],
      ["duplicate-command-replacement", "lookup-tool"],
    ]);
    expect(checked.written).toEqual([]);
  });

  it("requires an unquoted literal command in a replacement rule", async () => {
    await usePack(gate([{ command: "printf 'legacy report'" }]));
    await expect(compile(root, wardenRoot)).rejects.toMatchObject({
      pointer: "/capabilities/0/replaces/0/command",
      message: expect.stringContaining("unquoted command"),
    });
  });

  it("preserves invocations that fill in the bundled review Capability's command templates", async () => {
    await usePack([
      ...gate([
        { command: "warden check --rule review-gate --tier boundary --base main" },
        { command: "warden review brief --capability change-review --base main --head HEAD --requirements base.md changes.md" },
        { command: "warden check --rule old-review-gate --tier boundary --base main" },
        { command: "warden where example" },
        { command: "warden where example --capability" },
      ]),
      ...capability("lookup-tool", "tool", "lookup", ["warden where <query>"]),
    ]);
    const config = join(root, ".warden/config.yaml");
    const text = await readFile(config, "utf8");
    await writeFile(config, text.replace("tierBudgetMs:", '  - id: review\n    paths: ["**/*"]\ntierBudgetMs:'));
    const findings = checkConsistency(await loadRecords(root, wardenRoot), new Map());
    expect(findings.map(({ code, message }) => [code, message.split(". Next action")[0]])).toEqual([
      ["registered-command-replacement", "Capability review-gate would block the registered command warden check --rule review-gate --tier boundary --base main"],
      ["registered-command-replacement", "Capability review-gate would block the registered command warden review brief --capability change-review --base main --head HEAD --requirements base.md changes.md"],
      ["registered-command-replacement", "Capability review-gate would block the registered command warden where example"],
    ]);
  });

  it("a skill capability compiles to SKILL.md with every upheld statement and every command in order", async () => {
    await usePack(gate());
    expect((await compile(root, wardenRoot)).findings).toEqual([]);
    const lines = (await readFile(join(root, skillPath("review-gate")), "utf8")).split("\n");
    expect(lines[0]).toBe("---");
    expect(lines[1]).toMatch(HEADER);
    expect(lines.slice(2)).toEqual([
      'name: "review-gate"',
      'description: "Gate a unit before review. Use when a unit is ready for review."',
      "---",
      "# review-gate",
      "",
      "Gate a unit before review.",
      "",
      "## Upholds",
      "",
      "- no-comments: Source files carry no comments.",
      "- no-suppressions: Source files carry no inline suppressions and no skipped tests.",
      "",
      "## Steps",
      "",
      "1. `warden check --rule no-comments`",
      "2. `warden doctor`",
      "",
      "## Use this instead of",
      "",
      "- old-gate",
      "",
      "When a step fails, do its printed Next action, then run the step again. Fix the code, never the check.",
      "",
    ]);
  });

  it("front matter parses when purpose holds a colon, and a when ending in a period gets no second one", async () => {
    await usePack(capability("review-gate", "skill", "review", ["warden doctor"], [], "Gate: a unit, before review.", "a unit is ready for review."));
    expect((await compile(root, wardenRoot)).findings).toEqual([]);
    const text = await readFile(join(root, skillPath("review-gate")), "utf8");
    const front = parse(text.split("---\n")[1] as string) as Record<string, string>;
    expect({ name: front.name, description: front.description }).toEqual({ name: "review-gate", description: "Gate: a unit, before review. Use when a unit is ready for review." });
    expect(front.generated).toMatch(/^@generated by warden /);
  });

  it("doctor says to compile when the skill folder is missing, and then to link it, and each action clears its failure", async () => {
    await usePack(gate());
    const cli = (args: string[]) => execFileSync(process.execPath, [join(wardenRoot, "bin/warden.js"), ...args], { cwd: root, env: { ...process.env, WARDEN_HOME: home }, stdio: "ignore" });
    execFileSync("git", ["init", "-q", "-b", "main"], { cwd: root });
    execFileSync("git", ["config", "core.hooksPath", ".warden/generated/hooks"], { cwd: root });
    const skillLine = async () => (await doctor(await loadRecords(root, wardenRoot), true)).lines.find((l) => l.includes("skill review-gate"));
    const next = async () => (await doctor(await loadRecords(root, wardenRoot), true)).next;
    expect(await skillLine()).toMatch(/^FAIL  skill review-gate  /);
    expect(await next()).toBe("run warden compile, then run warden doctor");
    cli(["compile"]);
    const link = /^run (.*), then run warden doctor$/.exec((await next()) ?? "")?.[1];
    expect(link).toBe('(cd "$(git rev-parse --show-toplevel)" && mkdir -p .claude/skills && ln -s ../../.warden/generated/skills/review-gate .claude/skills/review-gate)');
    const nested = join(root, "nested");
    await mkdir(nested);
    execFileSync("sh", ["-c", link as string], { cwd: nested });
    expect(await skillLine()).toBe("ok    skill review-gate");
    expect(await next()).toBeUndefined();
  });

  it("requires a skill id with lowercase letters, digits, or hyphens", async () => {
    await usePack(capability("Review Gate", "skill", "review", ["warden doctor"]));
    await expect(compile(root, wardenRoot)).rejects.toMatchObject({ pointer: "/capabilities/0/id", message: expect.stringContaining("Next action: fix id at /capabilities/0") });
    await usePack(gate());
    expect((await compile(root, wardenRoot)).findings).toEqual([]);
  });

  it("retires a renamed skill through its existing link and preserves unrelated files", async () => {
    await usePack(gate());
    expect((await compile(root, wardenRoot)).findings).toEqual([]);
    const link = join(root, ".claude/skills/review-gate");
    await mkdir(join(link, ".."), { recursive: true });
    await symlink(`../../${SKILLS_DIR}/review-gate`, link);
    const unrelated = join(root, SKILLS_DIR, "review-gate", "notes.md");
    await writeFile(unrelated, "keep");
    expect(existsSync(join(link, "SKILL.md"))).toBe(true);
    await usePack(capability("change-review", "skill", "review", ["warden doctor"]));
    expect((await compile(root, wardenRoot)).findings).toEqual([]);
    expect(existsSync(join(link, "SKILL.md"))).toBe(false);
    expect(readLock(root).generated).not.toHaveProperty(skillPath("review-gate"));
    expect(existsSync(join(root, skillPath("change-review")))).toBe(true);
    expect(await readFile(unrelated, "utf8")).toBe("keep");
  });

  it("a skill without replaces has no Use this instead of section", async () => {
    await usePack(gate([]));
    expect((await compile(root, wardenRoot)).findings).toEqual([]);
    const text = await readFile(join(root, skillPath("review-gate")), "utf8");
    expect(text).toContain("2. `warden doctor`\n\nWhen a step fails");
    expect(text).not.toContain("## Use this instead of");
  });

  it("a Markdown file without front matter cannot carry a generated header", () => {
    expect(() => stamp("x/SKILL.md", "# x\n", "0.0.0", "h")).toThrow(Error);
    expect(stamp("x/SKILL.md", "---\nname: x\n---\n", "0.0.0", "h").split("\n").slice(2)).toEqual(["name: x", "---", ""]);
  });

  it("a tool capability emits no skill", async () => {
    await usePack(capability("where", "tool", "lookup", ["warden explain <id>"]));
    const { findings, written } = await compile(root, wardenRoot);
    expect(findings).toEqual([]);
    expect(written.filter((f) => f.startsWith(SKILLS_DIR))).toEqual([]);
    expect(existsSync(join(root, SKILLS_DIR))).toBe(false);
  });

  it("the skill is in the lock, and a hand edit is generated-drift", async () => {
    await usePack(gate());
    expect((await compile(root, wardenRoot)).findings).toEqual([]);
    for (const args of [["init", "-q", "-b", "main"], ["add", "-A"], ["-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null", "commit", "-qm", "seed"]]) execFileSync("git", args, { cwd: root });
    const file = skillPath("review-gate");
    expect(readLock(root).generated[file]).toMatch(/^[0-9a-f]{64}$/);
    await writeFile(join(root, file), `${await readFile(join(root, file), "utf8")}extra\n`);
    const drift = async () => (await findTampering(await loadRecords(root, wardenRoot), wardenRoot, "main", false)).filter((t) => t.detail === "generated-drift");
    expect(await drift()).toEqual([{ file, detail: "generated-drift" }]);
    execFileSync(process.execPath, [join(wardenRoot, "bin/warden.js"), "compile"], { cwd: root, env: { ...process.env, WARDEN_HOME: home }, stdio: "ignore" });
    expect(await drift()).toEqual([]);
  });

  it("a command that is not a warden subcommand fails as unknown-command", async () => {
    await usePack(capability("review-gate", "skill", "review", ["git push", "warden nosuch", "warden --version", "warden review nosuch", "warden check --rule x"]));
    const found = await checkCommands(await loadRecords(root, wardenRoot), wardenRoot);
    expect(found.map((f) => [f.code, f.record])).toEqual(Array.from({ length: 4 }, () => ["unknown-command", "review-gate"]));
    expect((await compile(root, wardenRoot)).findings.map((f) => f.code)).toEqual(Array(4).fill("unknown-command"));
    await usePack(capability("review-gate", "skill", "review", ["warden check --rule x", "warden review brief", "warden daemon install"]));
    expect(await checkCommands(await loadRecords(root, wardenRoot), wardenRoot)).toEqual([]);
  });

  it("a warden that cannot run is reported as warden-unrunnable, not unknown-command", async () => {
    await usePack(capability("review-gate", "skill", "review", ["warden check --rule x"]));
    const broken = await mkdtemp(join(tmpdir(), "warden-broken-"));
    const found = await checkCommands(await loadRecords(root, wardenRoot), broken);
    expect(found.map((f) => f.code)).toEqual(["warden-unrunnable"]);
    expect(found[0]?.message).toContain("Next action: run npm run build:dist");
  });
});
